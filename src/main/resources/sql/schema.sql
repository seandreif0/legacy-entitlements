CREATE SEQUENCE ENT_SEQ START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE BATCH_RUN_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE INTERNAL_USER (
  USER_ID        VARCHAR2(20)  NOT NULL PRIMARY KEY,
  FULL_NAME      VARCHAR2(120),
  DEPT_CODE      VARCHAR2(10),
  COST_CENTER    VARCHAR2(10),
  GRADE          NUMBER(2),
  STATUS         VARCHAR2(12)  DEFAULT 'ACTIVE',
  LAST_SEEN_DT   DATE
);

CREATE TABLE DATA_SET (
  DATASET_CODE   VARCHAR2(20)  NOT NULL PRIMARY KEY,
  DESCRIPTION    VARCHAR2(200),
  RESTRICTED_FLG CHAR(1)       DEFAULT 'N'
);

CREATE TABLE USER_ENTITLEMENT (
  ENT_ID         NUMBER(12)    NOT NULL PRIMARY KEY,
  USER_ID        VARCHAR2(20)  NOT NULL,
  DATASET_CODE   VARCHAR2(20)  NOT NULL,
  ACCESS_LVL     VARCHAR2(10)  NOT NULL,
  SOURCE         VARCHAR2(10)  DEFAULT 'BATCH',
  GRANTED_DT     DATE          DEFAULT SYSDATE
);

CREATE TABLE BATCH_RUN (
  RUN_ID         NUMBER(12)    NOT NULL PRIMARY KEY,
  JOB_NAME       VARCHAR2(40),
  EXTRACT_FILE   VARCHAR2(200),
  STARTED_DT     DATE,
  ENDED_DT       DATE,
  ROWS_READ      NUMBER(10),
  ROWS_REJECTED  NUMBER(10),
  USERS_REVOKED  NUMBER(10),
  STATUS         VARCHAR2(12)
);
